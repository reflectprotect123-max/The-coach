import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const require=createRequire(import.meta.url);
const Builder=require('./strength-builder.js');
const Loop=require('./coach-loop.js');
const runtime={};vm.createContext(runtime);
for(const file of ['library.js','session.js']) vm.runInContext(readFileSync(new URL(`athlete-runtime/${file}`,import.meta.url),'utf8'),runtime);
const old=Loop.buildSeed().templates.find(t=>t.id===Loop.IDS.tplStrength);
const before=JSON.stringify(old);
const result=Builder.convert(old);
assert.equal(JSON.stringify(old),before,'conversion must preserve original prescriptions');
assert.ok(result.warnings.some(w=>w.includes('reps/load/RIR')));
const plan=runtime.HybridLibrary.compile(result.template);
assert.ok(plan.blocks.some(b=>b.kind==='lift' && b.prescription==='3 x 8'));
const group=result.template.blocks.filter(b=>b.groupId);
assert.equal(group.length,2,'multi-exercise superset must not swallow next block');
assert.equal(group[0].groupId,group[1].groupId);
const pages=runtime.HybridSession.startSession({date:'2026-10-10',plan}).pages;
assert.ok(pages.length>0);
const mixed=Builder.convert({id:'mixed',blocks:[{type:'conditioning',heading:'Run'},{type:'text',heading:'Warm-up',notes:'Walk'}]});
assert.equal(mixed.template.blocks.length,1);
assert.equal(mixed.template.blocks[0].kind,'circuit');
assert.ok(mixed.warnings[0].includes('not supported'));
const native={...result.template,title:'Native title'};
assert.deepEqual(Builder.convert({...old,athleteTemplate:native}).template,native);
console.log('Strength adapter and upstream compilation passed');

if(process.env.BUILDER_BROWSER_URL) {
  const {chromium}=require('playwright');
  const browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(process.env.BUILDER_BROWSER_URL);
    await page.getByRole('button',{name:'Demo coach (offline)'}).click();
    await page.evaluate(()=>openSession(CoachLoop.IDS.tplStrength));
    await page.getByRole('button',{name:'Strength builder',exact:true}).click();
    const editor=page.getByRole('dialog',{name:'Coach strength session builder'});
    assert.equal(await editor.locator('iframe').count(),1,'only athlete preview may use an iframe');
    await editor.getByRole('heading',{name:'Session Builder',exact:true}).waitFor();
    await editor.getByRole('textbox',{name:'Session title',exact:true}).fill('Native builder test');
    await editor.getByRole('textbox',{name:'Session title',exact:true}).blur();
    await page.waitForFunction(()=>S.templates.find(t=>t.id===CoachLoop.IDS.tplStrength).athleteTemplate?.title==='Native builder test');
    const squat=editor.locator('.sb-block').filter({has:page.locator('input[value="Back Squat"]')});
    await squat.getByLabel('Target difficulty').selectOption('hard');
    await squat.getByLabel('Sets',{exact:true}).fill('4');
    await squat.getByLabel('Sets',{exact:true}).blur();
    await page.waitForFunction(()=>S.templates.find(t=>t.id===CoachLoop.IDS.tplStrength).athleteTemplate.blocks.some(b=>b.title==='Back Squat'&&b.setCount===4&&b.targetEffort==='hard'));
    const preview=page.frameLocator('iframe[title="Exact athlete session preview"]');
    await preview.getByRole('button',{name:'Start Session',exact:true}).click();
    await preview.locator('#logger:not(.hidden)').waitFor();
    const f=await editor.locator('iframe').elementHandle().then(handle=>handle.contentFrame());
    const session=await f.evaluate(()=>({title:S.session.title,pages:S.session.pages.length}));
    assert.ok(session.pages>1);
    await f.evaluate(()=>Logger.open({date:today(),letter:'B',plan:HybridLibrary.compile(HybridLibrary.template(S.library,S.libUi.tid))}));
    assert.equal(await f.evaluate(()=>S.session.pages.find(p=>p.title==='Back Squat').targetEffort),'hard');
    assert.equal(await f.evaluate(()=>S.session.pages.find(p=>p.title==='Back Squat').setCount),4);
    const saved=await page.evaluate(()=>JSON.stringify(S));
    await f.evaluate(()=>{Logger.setField('B','reps','8');Logger.setField('B','kg','100');Logger.setEffort('B',3);Logger.saveSet('B');});
    assert.equal(await f.evaluate(()=>S.session.logs.B.sets[0].logged),true);
    assert.equal(await page.evaluate(()=>JSON.stringify(S)),saved,'preview must not mutate coach state');
    if(process.env.BUILDER_SCREENSHOT) await page.screenshot({path:process.env.BUILDER_SCREENSHOT});
    await editor.getByRole('button',{name:'+ Add exercise',exact:true}).click();
    await editor.getByRole('searchbox',{name:'Search exercises'}).fill('Front Squat');
    assert.equal(await editor.locator('.sb-result').count(),1);
    await editor.locator('.sb-result').click();
    const front=editor.locator('.sb-block').filter({has:page.locator('input[value="Front Squat"]')});
    await front.waitFor();
    await editor.getByRole('button',{name:'+ Add completion circuit',exact:true}).click();
    await front.getByLabel('Rest (seconds)').fill('90');
    await front.getByLabel('Rest (seconds)').blur();
    await editor.getByRole('button',{name:'Move Front Squat up',exact:true}).click();
    await editor.getByRole('button',{name:'Move Front Squat up',exact:true}).click();
    await front.getByRole('button',{name:'Link next exercise as superset',exact:true}).click();
    const grouping=await page.evaluate(()=>S.templates.find(t=>t.id===CoachLoop.IDS.tplStrength).athleteTemplate.blocks.filter(b=>b.groupId).map(b=>({title:b.title,groupId:b.groupId})));
    assert.ok(grouping.some(b=>b.title==='Front Squat'));
    await front.getByRole('button',{name:'Unlink exercise',exact:true}).click();
    page.once('dialog',dialog=>dialog.accept());
    await front.getByRole('button',{name:'Delete Front Squat',exact:true}).click();
    assert.equal(await front.count(),0);
    await page.getByRole('button',{name:'Back to coach',exact:true}).click();
    await page.reload();
    assert.equal(await page.evaluate(()=>S.templates.find(t=>t.id===CoachLoop.IDS.tplStrength).athleteTemplate.title),'Native builder test');
    await page.setViewportSize({width:390,height:844});
    await page.evaluate(()=>openSession(CoachLoop.IDS.tplStrength));
    await page.getByRole('button',{name:'Continue strength draft',exact:true}).click();
    assert.ok(await page.evaluate(()=>document.getElementById('strengthBuilder').scrollWidth<=innerWidth),'mobile coach builder must not overflow horizontally');
    await page.getByRole('button',{name:'Back to coach',exact:true}).click();
    assert.deepEqual(errors,[]);
    console.log('Browser coach editing, actual logger, isolation, and reload passed');
  } finally {await browser.close();}
}
