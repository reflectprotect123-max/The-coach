import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const L=require('./coach-loop.js');
const state=L.buildSeed();
const options={athleteId:L.IDS.athleteDan,date:'2027-02-12',templateId:L.IDS.tplStrength};
assert.throws(()=>L.addCalendarSession(state,{...options,athleteId:'missing'}),/valid athlete/);
for(const date of ['','2027-02-30','2027-2-12','garbage']) assert.throws(()=>L.addCalendarSession(state,{...options,date}),/valid session date/);
const session=L.addCalendarSession(state,options);
assert.equal(session.published,false);
assert.equal(session.date,options.date);
assert.equal(L.addCalendarSession(state,options),null);
console.log('Calendar assignment validation and deduplication passed');

if(process.env.COACH_BROWSER_URL){
  const {chromium}=require('playwright');
  const browser=await chromium.launch({headless:true,args:['--no-sandbox'],...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:900}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(process.env.COACH_BROWSER_URL);
    await page.getByRole('button',{name:'Demo coach (offline)'}).click();
    await page.evaluate(()=>{
      const template=tpl(CoachLoop.IDS.tplStrength);
      template.athleteTemplate=StrengthBuilder.convert(template).template;
      go('athlete',{athleteId:CoachLoop.IDS.athleteDan,calMonth:'2027-02'});
      CoachViews.openAddFromLibrary('2027-02-12',CoachLoop.IDS.athleteDan);
    });
    let picker=page.getByRole('dialog',{name:'Add From Library',exact:true});
    const search=picker.getByRole('textbox',{name:'Search calendar sessions'});
    await search.fill('no such session');
    await picker.getByText('No matching sessions.',{exact:true}).waitFor();
    await search.fill('full body');
    assert.equal(await search.evaluate(el=>document.activeElement===el),true);
    assert.equal(await picker.locator('[data-calendar-template]').count(),1);
    await picker.getByText('Strength draft is local only; assigns original coach session.',{exact:true}).waitFor();
    await picker.getByLabel('Session date',{exact:true}).fill('2027-03-14');
    await picker.getByLabel('Session date',{exact:true}).blur();
    await picker.locator('[data-calendar-template]').click();
    const assigned=await page.evaluate(()=>S.sessions.find(s=>s.date==='2027-03-14'&&s.templateId===CoachLoop.IDS.tplStrength));
    assert.equal(assigned.athleteId,L.IDS.athleteDan);
    assert.equal(assigned.published,false);
    assert.equal(await page.locator('.calendar-monthbar b').textContent(),'March 2027');
    await page.evaluate(()=>CoachViews.openAddFromLibrary('2027-03-14',CoachLoop.IDS.athleteDan));
    assert.equal(await picker.locator(`[data-calendar-template="${L.IDS.tplStrength}"]`).isDisabled(),true);
    await page.evaluate(()=>CoachViews.pickLibraryTemplate(CoachLoop.IDS.tplStrength));
    await picker.getByText('This session is already scheduled for this athlete and date.',{exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>S.sessions.filter(s=>s.date==='2027-03-14'&&s.templateId===CoachLoop.IDS.tplStrength).length),1);
    await picker.getByRole('button',{name:'Close library picker'}).click();
    await page.evaluate(()=>{go('team',{teamId:CoachLoop.IDS.team,calMonth:'2027-04'});CoachViews.openAddFromLibrary('2027-04-15','',true);});
    const athletes=page.getByRole('dialog',{name:'Choose athlete',exact:true});
    await athletes.locator(`[data-athlete-id="${L.IDS.athleteDan}"]`).click();
    picker=page.getByRole('dialog',{name:'Add From Library',exact:true});
    await picker.getByLabel('Session date',{exact:true}).fill('');
    await picker.getByLabel('Session date',{exact:true}).blur();
    await picker.locator(`[data-calendar-template="${L.IDS.tplCond}"]`).click();
    await picker.getByText('Choose a valid session date',{exact:true}).waitFor();
    await picker.getByLabel('Session date',{exact:true}).fill('2027-04-15');
    await picker.getByLabel('Session date',{exact:true}).blur();
    await picker.locator(`[data-calendar-template="${L.IDS.tplCond}"]`).click();
    const teamSession=await page.evaluate(()=>S.sessions.find(s=>s.date==='2027-04-15'&&s.templateId===CoachLoop.IDS.tplCond));
    assert.equal(teamSession.athleteId,L.IDS.athleteDan);
    await page.reload();
    assert.ok(await page.evaluate(id=>S.sessions.some(s=>s.id===id),teamSession.id));
    await page.evaluate(()=>{openProgram(CoachLoop.IDS.program);openCellPick(3,7,'set');});
    const gridPicker=page.getByRole('dialog',{name:'Choose session template',exact:true});
    const gridSearch=gridPicker.getByRole('textbox',{name:'Search program sessions'});
    await gridSearch.fill('no matches');
    await gridPicker.getByText('No matching sessions',{exact:true}).waitFor();
    assert.equal(await gridPicker.locator('[data-program-template]').first().isVisible(),false);
    await gridSearch.fill('full body');
    assert.equal(await gridSearch.evaluate(el=>document.activeElement===el),true);
    assert.equal(await gridPicker.locator('[data-program-template]:not([hidden])').count(),1);
    await gridPicker.locator('[data-program-template]:not([hidden])').click();
    assert.equal(await page.evaluate(()=>prog(CoachLoop.IDS.program).cells[CoachLoop.cellKey(3,7)]),L.IDS.tplStrength);
    assert.deepEqual(errors,[]);
    console.log('Browser athlete/team/program search, dates, duplicate guards, draft warning, and persistence passed');
  }finally{await browser.close();}
}
